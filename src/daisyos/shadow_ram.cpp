// Writes a length-counted run of text from the cursor, scrolling as it fills
// the screen and batching each row into a single video message rather than one
// message per character.
void WriteString(const char* str, uint16_t len) {
  if (len > 1000) {
    len = 1000;
  }

  uint16_t cursor_cell =
      shadow_ram.cursor_location.y * VID_WIDTH + shadow_ram.cursor_location.x;
  uint16_t remaining = len;
  const char* ptr = str;

  while (remaining > 0) {
    uint16_t space_left = (VID_WIDTH * VID_HEIGHT) - cursor_cell;

    if (space_left == 0) {
      Scrollscr();
      VideoMsgSendScrollScreen();
      cursor_cell = (VID_HEIGHT - 1) * VID_WIDTH;
      space_left = VID_WIDTH;
    }

    uint16_t to_write = (remaining < space_left) ? remaining : space_left;

    uint16_t written = 0;
    while (written < to_write) {
      uint8_t chunk_size =
          ((to_write - written) > 58) ? 58 : (to_write - written);
      PutStringAt(cursor_cell + written, (char*)(ptr + written), chunk_size);
      memset(&shadow_ram.attrbmem[cursor_cell + written],
             shadow_ram.reverse_mode ? 0xFF : 0x00, chunk_size);
      written += chunk_size;
    }

    cursor_cell += to_write;
    ptr += to_write;
    remaining -= to_write;

    if (remaining > 0 && cursor_cell >= (VID_WIDTH * VID_HEIGHT)) {
      Scrollscr();
      VideoMsgSendScrollScreen();
      cursor_cell = (VID_HEIGHT - 1) * VID_WIDTH;
    }
  }

  shadow_ram.cursor_location.x = cursor_cell % VID_WIDTH;
  shadow_ram.cursor_location.y = cursor_cell / VID_WIDTH;

  VideoMsgSendLocateCursor(shadow_ram.cursor_location.x,
                           shadow_ram.cursor_location.y);
}

// Inserts a character at the cursor, pushing the rest of the line right. If the
// line already continues onto the next row the overflow is carried into it;
// otherwise a new continuation row is started, so long program lines survive
// editing in the middle.
void InsertCharAtCursor(uint8_t ch) {
  uint8_t x = shadow_ram.cursor_location.x;
  uint8_t y = shadow_ram.cursor_location.y;
  uint16_t lineStart = y * VID_WIDTH;

  uint8_t overflow = shadow_ram.videomem[lineStart + VID_WIDTH - 1];

  for (int i = VID_WIDTH - 1; i > x; i--) {
    shadow_ram.videomem[lineStart + i] = shadow_ram.videomem[lineStart + i - 1];
    shadow_ram.attrbmem[lineStart + i] = shadow_ram.attrbmem[lineStart + i - 1];
  }

  shadow_ram.videomem[lineStart + x] = ch;
  shadow_ram.attrbmem[lineStart + x] = shadow_ram.reverse_mode ? 0xFF : 0x00;

  VideoMsgSendPutStringAtCell(
      lineStart + x, (char*)&shadow_ram.videomem[lineStart + x], VID_WIDTH - x);

  bool hasExistingContinue = shadow_ram.continue_line[y];
  bool isAlreadyContinuation = (y > 0) && shadow_ram.continue_line[y - 1];
  bool canCreateContinue = !isAlreadyContinuation && (y < VID_HEIGHT - 1);

  if (hasExistingContinue) {
    uint16_t nextLineStart = (y + 1) * VID_WIDTH;

    for (int i = VID_WIDTH - 1; i > 0; i--) {
      shadow_ram.videomem[nextLineStart + i] =
          shadow_ram.videomem[nextLineStart + i - 1];
      shadow_ram.attrbmem[nextLineStart + i] =
          shadow_ram.attrbmem[nextLineStart + i - 1];
    }

    shadow_ram.videomem[nextLineStart] = overflow;
    shadow_ram.attrbmem[nextLineStart] = 0;

    VideoMsgSendPutStringAtCell(
        nextLineStart, (char*)&shadow_ram.videomem[nextLineStart], VID_WIDTH);
  } else if (canCreateContinue && overflow != ' ' && overflow != 0) {
    uint16_t nextLineStart = (y + 1) * VID_WIDTH;

    for (int i = VID_WIDTH - 1; i > 0; i--) {
      shadow_ram.videomem[nextLineStart + i] =
          shadow_ram.videomem[nextLineStart + i - 1];
      shadow_ram.attrbmem[nextLineStart + i] =
          shadow_ram.attrbmem[nextLineStart + i - 1];
    }

    shadow_ram.videomem[nextLineStart] = overflow;
    shadow_ram.attrbmem[nextLineStart] = 0;

    shadow_ram.continue_line[y] = true;
    shadow_ram.continue_line[y + 1] = false;

    VideoMsgSendPutStringAtCell(
        nextLineStart, (char*)&shadow_ram.videomem[nextLineStart], VID_WIDTH);
  }

  shadow_ram.cursor_location.x++;
  if (shadow_ram.cursor_location.x >= VID_WIDTH) {
    if (shadow_ram.continue_line[y] && y < VID_HEIGHT - 1) {
      shadow_ram.cursor_location.x = 0;
      shadow_ram.cursor_location.y++;
    } else {
      shadow_ram.cursor_location.x = VID_WIDTH - 1;
    }
  }
  VideoMsgSendLocateCursor(shadow_ram.cursor_location.x,
                           shadow_ram.cursor_location.y);
}

// Deletes the character at the cursor, pulling the rest of the line left and
// drawing back any text from a continuation row.
void DeleteCharAtCursor(void) {
  uint8_t x = shadow_ram.cursor_location.x;
  uint8_t y = shadow_ram.cursor_location.y;
  uint16_t lineStart = y * VID_WIDTH;

  for (int i = x; i < VID_WIDTH - 1; i++) {
    shadow_ram.videomem[lineStart + i] = shadow_ram.videomem[lineStart + i + 1];
    shadow_ram.attrbmem[lineStart + i] = shadow_ram.attrbmem[lineStart + i + 1];
  }

  if (shadow_ram.continue_line[y] && y < VID_HEIGHT - 1) {
    uint16_t nextStart = (y + 1) * VID_WIDTH;
    shadow_ram.videomem[lineStart + VID_WIDTH - 1] =
        shadow_ram.videomem[nextStart];
    shadow_ram.attrbmem[lineStart + VID_WIDTH - 1] =
        shadow_ram.attrbmem[nextStart];

    for (int i = 0; i < VID_WIDTH - 1; i++) {
      shadow_ram.videomem[nextStart + i] =
          shadow_ram.videomem[nextStart + i + 1];
      shadow_ram.attrbmem[nextStart + i] =
          shadow_ram.attrbmem[nextStart + i + 1];
    }
    shadow_ram.videomem[nextStart + VID_WIDTH - 1] = ' ';
    shadow_ram.attrbmem[nextStart + VID_WIDTH - 1] =
        shadow_ram.reverse_mode ? 0xFF : 0x00;

    VideoMsgSendPutStringAtCell(lineStart + x,
                                (char*)&shadow_ram.videomem[lineStart + x],
                                VID_WIDTH - x);
    VideoMsgSendPutStringAtCell(
        nextStart, (char*)&shadow_ram.videomem[nextStart], VID_WIDTH);
  } else {
    shadow_ram.videomem[lineStart + VID_WIDTH - 1] = ' ';
    shadow_ram.attrbmem[lineStart + VID_WIDTH - 1] =
        shadow_ram.reverse_mode ? 0xFF : 0x00;

    VideoMsgSendPutStringAtCell(lineStart + x,
                                (char*)&shadow_ram.videomem[lineStart + x],
                                VID_WIDTH - x);
  }
}

// Switches one row between the text and graphics character sets. The selection
// lives in the low bits of the row's first attribute byte.
void SetLineGfxMode(uint8_t line, bool isGfx) {
  if (line >= VID_HEIGHT) {
    return;
  }

  uint16_t lineStart = line * VID_WIDTH;

  if (isGfx) {
    shadow_ram.attrbmem[lineStart] |= 0x01;
  } else {
    shadow_ram.attrbmem[lineStart] &= ~0x01;
  }

  VideoMsgSendPutAttribsAtCell(lineStart,
                               (char*)&shadow_ram.attrbmem[lineStart], 1);
}

// Rotates a band of rows sideways with wraparound, normalising the shift so any
// direction value works.
void ScrollX(uint8_t y, uint8_t height, int8_t direction) {
  if (y >= VID_HEIGHT || height == 0 || direction == 0) {
    return;
  }
  int s = (int)direction % (int)VID_WIDTH;
  if (s < 0) s += VID_WIDTH;
  uint8_t shift = (uint8_t)s;
  uint8_t tmp[VID_WIDTH];
  for (uint8_t row = 0; row < height; row++) {
    uint8_t cy = y + row;
    if (cy >= VID_HEIGHT) {
      break;
    }
    uint8_t* line = &shadow_ram.videomem[cy * VID_WIDTH];
    memcpy(tmp, line, VID_WIDTH);
    memcpy(line + shift, tmp, VID_WIDTH - shift);
    memcpy(line, tmp + VID_WIDTH - shift, shift);
  }
  VideoMsgSendScrollX(y, height, direction);
}

// Reads a glyph's current bitmap from the mirror.
void GetCharDef(uint8_t ch, uint8_t* bitrows) {
  memcpy(bitrows, shadow_ram.char_defs[ch], 8);
}

// Reads a glyph's original ROM bitmap, ignoring any redefinition.
void GetCharROMDef(uint8_t ch, uint8_t* bitrows) {
  for (uint8_t row = 0; row < 8; row++) {
    bitrows[row] = pgm_read_byte(&charROMShadow[row * 256 + ch]);
  }
}

// Restores one text glyph in the mirror from ROM.
void ResetCharDef(uint8_t ch) { GetCharROMDef(ch, shadow_ram.char_defs[ch]); }

// Records a redefined glyph in the mirror.
void SetCharDef(uint8_t ch, const uint8_t* bitrows) {
  memcpy(shadow_ram.char_defs[ch], bitrows, 8);
}

