// Decodes a block-graphic character into masks of which quadrants are solid and
// which are dithered. Non-graphic characters decode to empty.
static inline void extractPixelBits(uint8_t ch, uint8_t& solid,
                                    uint8_t& dither) {
  if (ch <= 15) {
    solid = ch;
    dither = 0;
  } else if (ch >= 160 && ch <= 175) {
    solid = 0;
    dither = ch - 160;
  } else if (ch >= 176 && ch <= 225) {
    uint8_t sd = pgm_read_byte(&mixedRev[ch - 176]);
    solid = sd >> 4;
    dither = sd & 0x0F;
  } else {
    solid = 0;
    dither = 0;
  }
}

// Inverse of extractPixelBits: the character code that renders a given mix of
// solid and dithered quadrants.
static inline uint8_t packPixelBits(uint8_t solid, uint8_t dither) {
  if (dither == 0) {
    return solid;
  }
  if (solid == 0) {
    return 160 + dither;
  }
  return pgm_read_byte(&mixedFwd[(solid << 4) | dither]);
}

// Sets up the local mirror of the video board's state. DaisyOS keeps a full
// copy of screen memory, attributes, and glyph definitions so it can read the
// screen back and compute updates without ever querying DaisyVideo, which is a
// write-only link. Also synthesises the mixed solid/dither glyphs absent from
// the ROM font.
void InitShadowRam(void) {
  memset(&shadow_ram, 0, sizeof(shadow_ram));
  shadow_ram.cursor_mode = AutoAdvance;
  shadow_ram.scroll_mode = AutoScroll;
  shadow_ram.reverse_mode = false;

  for (uint16_t ch = 0; ch < 256; ch++) {
    for (uint8_t row = 0; row < 8; row++) {
      uint8_t val = pgm_read_byte(&charROMShadow[row * 256 + ch]);
      shadow_ram.char_defs[ch][row] = val;
      shadow_ram.gfx_defs[ch][row] = val;
    }
  }

  for (uint8_t i = 0; i < 50; i++) {
    uint8_t sd = pgm_read_byte(&mixedRev[i]);
    uint8_t solidBits = sd >> 4, ditherBits = sd & 0x0F;
    uint8_t ch = 176 + i;
    for (uint8_t row = 0; row < 8; row++) {
      uint8_t leftBit = (row < 4) ? 0 : 2;
      uint8_t rightBit = (row < 4) ? 1 : 3;
      uint8_t leftState = (solidBits >> leftBit) & 1
                              ? 1
                              : ((ditherBits >> leftBit) & 1 ? 2 : 0);
      uint8_t rightState = (solidBits >> rightBit) & 1
                               ? 1
                               : ((ditherBits >> rightBit) & 1 ? 2 : 0);
      uint8_t lb = 0;
      if (leftState == 1) {
        lb = 0xF0;
      } else if (leftState == 2) {
        lb = (row & 1) ? 0x50 : 0xA0;
      }
      uint8_t rb = 0;
      if (rightState == 1) {
        rb = 0x0F;
      } else if (rightState == 2) {
        rb = (row & 1) ? 0x05 : 0x0A;
      }
      shadow_ram.char_defs[ch][row] = lb | rb;
      shadow_ram.gfx_defs[ch][row] = lb | rb;
    }
  }
}

// Selects whether newly written characters are reverse video.
void SetReverseMode(bool reverse) {
  shadow_ram.reverse_mode = reverse;
  VideoMsgSendSetReverseMode(reverse);
}

// True if newly written characters will be in reverse video.
bool GetReverseMode(void) { return shadow_ram.reverse_mode; }

// Inverts the entire display without touching per-cell attributes.
void SetReverseScreen(bool reverse) {
  shadow_ram.reverse_mode = reverse;
  memset(shadow_ram.attrbmem, reverse ? 0xFF : 0x00,
         sizeof(shadow_ram.attrbmem));
  VideoMsgSendReverseScreen(reverse);
}

// Scrolls the mirror up one row and blanks the bottom. The caller sends the
// matching command to the video board.
void Scrollscr(void) {
  uint8_t attrValue = shadow_ram.reverse_mode ? 0xFF : 0x00;
  for (uint8_t line = 1; line < VID_HEIGHT; line++) {
    memcpy(&shadow_ram.videomem[(line - 1) * VID_WIDTH],
           &shadow_ram.videomem[VID_WIDTH * line], VID_WIDTH);
    memcpy(&shadow_ram.attrbmem[(line - 1) * VID_WIDTH],
           &shadow_ram.attrbmem[VID_WIDTH * line], VID_WIDTH);
    shadow_ram.continue_line[line - 1] = shadow_ram.continue_line[line];
  }
  memset(&shadow_ram.videomem[(VID_HEIGHT - 1) * VID_WIDTH], 0x00, VID_WIDTH);
  memset(&shadow_ram.attrbmem[(VID_HEIGHT - 1) * VID_WIDTH], attrValue,
         VID_WIDTH);
  shadow_ram.continue_line[VID_HEIGHT - 1] = false;
}

// Fills the screen with one character and resets attributes.
void Clrscr(byte val) {
  memset(shadow_ram.videomem, val, sizeof(shadow_ram.videomem));
  memset(shadow_ram.attrbmem, shadow_ram.reverse_mode ? 0xFF : 0x00,
         sizeof(shadow_ram.attrbmem));
  memset(shadow_ram.continue_line, 0, sizeof(shadow_ram.continue_line));
  VideoMsgSendClearScreen(val);
}

// Writes a character to a cell without moving the cursor or changing the
// cell's attribute.
void PlotChar(uint8_t x, uint8_t y, uint8_t ch) {
  if (x < VID_WIDTH && y < VID_HEIGHT) {
    uint16_t cell = x + y * VID_WIDTH;
    shadow_ram.videomem[cell] = ch;
    VideoMsgSendPlotChar(x, y, ch);
  }
}

// Fills a run of cells, wrapping onto following rows.
void FillCells(uint8_t x, uint8_t y, uint8_t ch, uint8_t count) {
  if (count == 0 || x >= VID_WIDTH || y >= VID_HEIGHT) {
    return;
  }
  uint16_t cell = (uint16_t)x + (uint16_t)y * VID_WIDTH;
  uint16_t available = (VID_WIDTH * VID_HEIGHT) - cell;
  if (count > available) {
    count = (uint8_t)available;
  }
  if (count == 0) {
    return;
  }
  memset(&shadow_ram.videomem[cell], ch, count);
  memset(&shadow_ram.attrbmem[cell], shadow_ram.reverse_mode ? 0xFF : 0x00,
         count);
  VideoMsgSendFillCells(x, y, ch, count);
}

// Mirrors a rectangle fill locally, cycling the character range exactly as the
// video board does so the two copies stay in step.
void FillBlockShadow(uint8_t x, uint8_t y, uint8_t w, uint8_t h,
                     uint8_t startChar, uint8_t endChar) {
  uint8_t ch = startChar;
  uint8_t attrib = shadow_ram.reverse_mode ? 0xFF : 0x00;
  for (uint8_t row = 0; row < h && (y + row) < VID_HEIGHT; row++) {
    uint16_t cell = (uint16_t)x + (uint16_t)(y + row) * VID_WIDTH;
    for (uint8_t col = 0; col < w && (x + col) < VID_WIDTH; col++) {
      shadow_ram.videomem[cell + col] = ch;
      shadow_ram.attrbmem[cell + col] = attrib;
      if (ch == endChar) {
        ch = startChar;
      } else {
        ch++;
      }
    }
  }
}

// Writes one character at the cursor and advances it, wrapping and scrolling at
// the edges. Updates both the mirror and the display.
void Chrout(uint8_t ascii) {
  if (ascii == 13) {
    Newline();
    return;
  }
  VideoMsgSendChrOut(ascii);
  if (ascii <= 255) {
    uint16_t cell = shadow_ram.cursor_location.x +
                    (shadow_ram.cursor_location.y * VID_WIDTH);
    shadow_ram.videomem[cell] = ascii;
    shadow_ram.attrbmem[cell] = shadow_ram.reverse_mode ? 0xFF : 0x00;
    if (shadow_ram.cursor_mode == AutoAdvance) {
      shadow_ram.cursor_location.x++;
      if (shadow_ram.cursor_location.x >= VID_WIDTH) {
        shadow_ram.cursor_location.x = 0;
        shadow_ram.cursor_location.y++;
        if (shadow_ram.cursor_location.y >= VID_HEIGHT) {
          if (shadow_ram.scroll_mode == AutoScroll) {
            Scrollscr();
          }
          shadow_ram.cursor_location.x = 0;
          shadow_ram.cursor_location.y = VID_HEIGHT - 1;
        }
        shadow_ram.continue_line[shadow_ram.cursor_location.y - 1] = true;
        shadow_ram.continue_line[shadow_ram.cursor_location.y] = false;
        if (shadow_ram.cursor_location.y >= 2) {
          shadow_ram.continue_line[shadow_ram.cursor_location.y - 2] = false;
        }
      }
    }
  }
}

// Chrout with the target cell forced to reverse video.
void chrout_reverse(uint8_t ascii) {
  shadow_ram.attrbmem[shadow_ram.cursor_location.y * VID_WIDTH] = 0xff;
  Chrout(ascii);
}

// Moves the cursor, ignoring coordinates that fall off-screen.
void LocateCursor(int x, int y) {
  if (x != shadow_ram.cursor_location.x) {
    if (x >= 0 && x < VID_WIDTH) {
      shadow_ram.cursor_location.x = x;
    }
  }
  if (y != shadow_ram.cursor_location.y) {
    if (y >= 0 && y < VID_HEIGHT) {
      shadow_ram.cursor_location.y = y;
    }
  }
  VideoMsgSendLocateCursor(x, y);
}

// Writes a NUL-terminated string at the cursor.
void PrintStr(char* string) {
  while (*string) {
    Chrout(*string++);
  }
  delayMicroseconds(3000);
}
// Writes a string horizontally centred on a row.
void CenterStr(char* string, uint8_t y) {
  uint8_t x = 20 - (uint8_t)strlen(string) / 2;
  LocateCursor(x, y);
  PrintStr(string);
}

// Starts a new line, scrolling if that runs off the bottom.
void Newline(void) {
  VideoMsgSendNewline();
  delayMicroseconds(3000);
  delayMicroseconds(3000);
  shadow_ram.cursor_location.x = 0;
  uint8_t old_line = shadow_ram.cursor_location.y++;
  if (HasContinue(old_line)) {
    shadow_ram.cursor_location.y++;
    VideoMsgSendNewline();
  }
  if (shadow_ram.cursor_location.y >= VID_HEIGHT) {
    if (shadow_ram.scroll_mode == AutoScroll) {
      Scrollscr();
    }
    shadow_ram.cursor_location.x = 0;
    shadow_ram.cursor_location.y = VID_HEIGHT - 1;
  }
}

// Moves the cursor one cell, clamping at the screen edges.
void MoveCursor(CursorDirection direction) {
  VideoMsgSendCursorMove(direction);
  switch (direction) {
    case kCursorUp: {
      shadow_ram.cursor_location.y--;
      if (shadow_ram.cursor_location.y < 0) {
        shadow_ram.cursor_location.y = 0;
      }
      break;
    }
    case kCursorRight: {
      shadow_ram.cursor_location.x++;
      if (shadow_ram.cursor_location.x == VID_WIDTH) {
        if (shadow_ram.cursor_location.y == VID_HEIGHT - 1) {
          if (shadow_ram.scroll_mode == AutoScroll) {
            Scrollscr();
          }
          shadow_ram.cursor_location.x = 0;
        } else {
          shadow_ram.cursor_location.x = 0;
          shadow_ram.cursor_location.y++;
        }
      }
      break;
    }
    case kCursorDown: {
      shadow_ram.cursor_location.y++;
      if (shadow_ram.cursor_location.y == VID_HEIGHT) {
        if (shadow_ram.scroll_mode == AutoScroll) {
          Scrollscr();
        }
        shadow_ram.cursor_location.y = VID_HEIGHT - 1;
      }
      break;
    }
    case kCursorLeft: {
      shadow_ram.cursor_location.x--;
      if (shadow_ram.cursor_location.x < 0) {
        if (shadow_ram.cursor_location.y != 0) {
          shadow_ram.cursor_location.x = VID_WIDTH - 1;
          shadow_ram.cursor_location.y--;
        } else {
          shadow_ram.cursor_location.x = 0;
        }
      }
      break;
    }
    default:
      break;
  }
}

// Inverts the cursor cell -- this is how the cursor is drawn, so no character
// underneath needs saving.
void ToggleAttribute(void) {
  uint16_t cell =
      (40 * shadow_ram.cursor_location.y) + shadow_ram.cursor_location.x;
  shadow_ram.attrbmem[cell] = ~shadow_ram.attrbmem[cell];
  VideoMsgSendPutAttribsAtCell(cell, (char*)&shadow_ram.attrbmem[cell], 1);
}

