// Reads a screen row out of the mirror as a NUL-terminated string, mapping the
// blank cell code to a space so the caller gets printable text.
bool GetVideoRamLine(uint8_t line, char* str) {
  memcpy(str, &shadow_ram.videomem[line * VID_WIDTH], VID_WIDTH);
  for (uint8_t i = 0; i < VID_WIDTH; i++) {
    if (str[i] == 0) {
      str[i] = ' ';
    }
  }
  str[VID_WIDTH] = '\0';
}

