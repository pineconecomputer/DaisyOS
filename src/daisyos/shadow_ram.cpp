// Character currently in a cell, read from the mirror.
uint8_t GetCharAt(uint8_t x, uint8_t y) {
  if (x >= VID_WIDTH || y >= VID_HEIGHT) {
    return 0;
  }
  return shadow_ram.videomem[x + y * VID_WIDTH];
}

// Sets one cell's video attribute without changing its character.
void SetAttribAt(uint8_t x, uint8_t y, uint8_t reversed) {
  if (x >= VID_WIDTH || y >= VID_HEIGHT) {
    return;
  }
  uint16_t cell = (uint16_t)x + (uint16_t)y * VID_WIDTH;
  uint8_t attr = reversed ? 0xFF : 0x00;
  shadow_ram.attrbmem[cell] = attr;
  VideoMsgSendPutAttribsAtCell(cell, (char*)&shadow_ram.attrbmem[cell], 1);
}

// Reads one cell's video attribute.
uint8_t GetAttribAt(uint8_t x, uint8_t y) {
  if (x >= VID_WIDTH || y >= VID_HEIGHT) {
    return 0;
  }
  return shadow_ram.attrbmem[x + y * VID_WIDTH] ? 1 : 0;
}

// Updates one pixel in the mirror only, for callers that will send their own
// batched drawing command.
void UpdateShadowPixel(uint8_t px, uint8_t py, uint8_t on) {
  uint8_t cx = px >> 1;
  uint8_t cy = py >> 1;
  if (cx >= VID_WIDTH || cy >= VID_HEIGHT) {
    return;
  }
  uint16_t cell = cx + cy * VID_WIDTH;
  uint8_t solid, dither;
  extractPixelBits(shadow_ram.videomem[cell], solid, dither);
  uint8_t mask = 1 << ((px & 1) | ((py & 1) << 1));
  solid &= ~mask;
  dither &= ~mask;
  if (on == 1) {
    solid |= mask;
  } else if (on == 2) {
    dither |= mask;
  }
  shadow_ram.videomem[cell] = packPixelBits(solid, dither);
}

// Sets one pixel in both the mirror and the display. Reads the cell's existing
// quadrants first so the other three pixels sharing it are preserved.
void PlotPixel(uint8_t px, uint8_t py, uint8_t on) {
  uint8_t cx = px >> 1;
  uint8_t cy = py >> 1;
  if (cx >= VID_WIDTH || cy >= VID_HEIGHT) {
    return;
  }
  uint16_t cell = cx + cy * VID_WIDTH;
  uint8_t solid, dither;
  extractPixelBits(shadow_ram.videomem[cell], solid, dither);
  uint8_t mask = 1 << ((px & 1) | ((py & 1) << 1));
  solid &= ~mask;
  dither &= ~mask;
  if (on == 1) {
    solid |= mask;
  } else if (on == 2) {
    dither |= mask;
  }
  shadow_ram.videomem[cell] = packPixelBits(solid, dither);
  VideoMsgSendSetPixel(px, py, on);
}

// Reads a pixel back as off, solid, or dithered.
uint8_t ReadPixelState(uint8_t px, uint8_t py) {
  uint8_t cx = px >> 1;
  uint8_t cy = py >> 1;
  if (cx >= VID_WIDTH || cy >= VID_HEIGHT) {
    return 0;
  }
  uint8_t ch = shadow_ram.videomem[cx + cy * VID_WIDTH];
  uint8_t solid, dither;
  extractPixelBits(ch, solid, dither);
  uint8_t mask = 1 << ((px & 1) | ((py & 1) << 1));
  if (solid & mask) {
    return 1;
  }
  if (dither & mask) {
    return 2;
  }
  return 0;
}
