// Returns the cursor cell to normal video.
void ClearAttribute(void) {
  uint16_t cell =
      (40 * shadow_ram.cursor_location.y) + shadow_ram.cursor_location.x;
  shadow_ram.attrbmem[cell] = shadow_ram.reverse_mode ? 0xFF : 0x00;
  VideoMsgSendPutAttribsAtCell(cell, (char*)&shadow_ram.attrbmem[cell], 1);
}

